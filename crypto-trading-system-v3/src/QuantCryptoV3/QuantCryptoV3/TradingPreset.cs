/// <summary>
/// Согласованный набор настроек.
///
/// Существует потому, что тридцать два поля по отдельности разумны, а вместе легко
/// образуют сочетание, в котором не проходит ни один сигнал. Пресет — это утверждение,
/// что конкретный набор посчитан целиком: и экономика входа, и ширина стопа, и порог
/// спреда, который обязан двигаться вместе с ней.
/// </summary>
public enum TradingPreset
{
    /// <summary>Значения полей используются как есть, ничего не перезаписывается.</summary>
    Manual = 0,

    /// <summary>Крипта на пятиминутках: самый малый таймфрейм, на котором сходится экономика.</summary>
    CryptoM5 = 1,

    /// <summary>Крипта на пятнадцатиминутках: реже сделки, заметно дешевле издержки.</summary>
    CryptoM15 = 2,

    /// <summary>
    /// Несколько классов активов на пятиминутках: крипта, золото, индексы.
    ///
    /// Единственный честный способ торговать чаще, не снижая планку, — больше НЕЗАВИСИМЫХ
    /// возможностей (фундаментальный закон Гринольда: IR = IC × √N). Крипта между собой
    /// коррелирует на 0.7–0.9, и пять монет дают немногим больше одной; золото и индексы —
    /// другие рынки с другими причинами движения.
    /// </summary>
    MultiAssetM5 = 3,
}
